#!/usr/bin/env python3
"""Writes gpu/shaders/v3_blend_weights.glsl, the weights of the learned-blend nets: Settings::v3Blend = 1 + 3 * set + net (net 0, 1, 2 = A, B, C), set = the position of the file triple.

    export_glsl.py A.npz B.npz C.npz [A2.npz B2.npz C2.npz ...] [-o gpu/shaders/v3_blend_weights.glsl]     (3 * k files, k = 1..5, set by set; today k = 2: the committed header)
    export_glsl.py --zeros [-o ...]          (six zero nets: each net then equals the rule up to the 1e-3 floor)

Each .npz holds float32 W1 [8][NI], b1 [8], W2 [K][8], b2 [K]; A and B: NI 25, K 4; C: NI 34, K 6 (SPEC section 4; gpu/V3.md 3.16 "As built (learned blend)").
Layout of the header (net v = 0..N-1 for v3Blend v + 1; every net padded with zeros to NI 34, K 6; N = V3B_NETS = 3 * k):
    V3B_W1[(v*8 + j)*34 + i]   V3B_B1[v*8 + j]   V3B_W2[(v*6 + k)*8 + j]   V3B_B2[v*6 + k]
The header also holds `const int V3B_NETS = N;`: framegen.h's kV3BlendMax must equal it (gpu/meson.build checks that when it configures). N <= 15 (the synth's variant field is 4 bits).
"""
import argparse, os, sys
import numpy as np

H, NIMAX, KMAX = 8, 34, 6
SHAPES = [(25, 4), (25, 4), (34, 6)]   # per set: nets A, B, C

def load(path, ni, k):
    z = np.load(path)
    w1, b1, w2, b2 = (np.asarray(z[n], np.float32) for n in ("W1", "b1", "W2", "b2"))
    for name, a, shape in (("W1", w1, (H, ni)), ("b1", b1, (H,)), ("W2", w2, (k, H)), ("b2", b2, (k,))):
        if a.shape != shape:
            sys.exit(f"{path}: {name} has shape {a.shape}, expected {shape}")
        if not np.all(np.isfinite(a)):
            sys.exit(f"{path}: {name} is not finite")
    return w1, b1, w2, b2

def pad(nets):
    n = len(nets)
    W1 = np.zeros((n, H, NIMAX), np.float32); B1 = np.zeros((n, H), np.float32)
    W2 = np.zeros((n, KMAX, H), np.float32); B2 = np.zeros((n, KMAX), np.float32)
    for v, (w1, b1, w2, b2) in enumerate(nets):
        W1[v, :, :w1.shape[1]] = w1; B1[v] = b1
        W2[v, :w2.shape[0]] = w2; B2[v, :b2.shape[0]] = b2
    return W1, B1, W2, B2

def arr(name, a):
    f = a.reshape(-1)
    body = ",\n    ".join(", ".join(repr(float(x)) if x != 0 else "0.0" for x in f[i:i + 8]) for i in range(0, len(f), 8))
    return f"const float {name}[{len(f)}] = float[{len(f)}](\n    {body});\n"

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("npz", nargs="*")
    ap.add_argument("--zeros", action="store_true")
    ap.add_argument("-o", default=os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "shaders", "v3_blend_weights.glsl"))
    a = ap.parse_args()
    if a.zeros:
        nets = [(np.zeros((H, ni), np.float32), np.zeros(H, np.float32), np.zeros((k, H), np.float32), np.zeros(k, np.float32)) for ni, k in SHAPES * 2]
    elif len(a.npz) in (3, 6, 9, 12, 15):
        nets = [load(p, *SHAPES[i % 3]) for i, p in enumerate(a.npz)]
    else:
        sys.exit("usage: export_glsl.py A.npz B.npz C.npz [A2.npz B2.npz C2.npz ...] (3, 6, 9, 12 or 15 files) [-o out.glsl]   or   --zeros")
    W1, B1, W2, B2 = pad(nets)
    src = "all zeros: every net equals the rule up to the 1e-3 floor" if a.zeros else "weights of " + ", ".join(a.npz)
    out = ("// GENERATED by gpu/ml/blend/export_glsl.py (" + src + "). Do not edit.\n"
           "// Variant v = 0..V3B_NETS-1 (Settings::v3Blend v + 1 = 1 + 3 * weight set + net, net 0, 1, 2 = A, B, C), every net padded with zeros to NI 34, K 6 (gpu/V3.md 3.16 \"As built (learned blend)\"):\n"
           "//   V3B_W1[(v*8 + j)*34 + i]  V3B_B1[v*8 + j]  V3B_W2[(v*6 + k)*8 + j]  V3B_B2[v*6 + k]\n"
           "// framegen.h's kV3BlendMax must equal V3B_NETS (gpu/meson.build checks it).\n"
           f"const int V3B_NETS = {len(nets)};\n"
           + arr("V3B_W1", W1) + arr("V3B_B1", B1) + arr("V3B_W2", W2) + arr("V3B_B2", B2))
    with open(a.o, "w") as f:
        f.write(out)

if __name__ == "__main__":
    main()
