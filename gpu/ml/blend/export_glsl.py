#!/usr/bin/env python3
"""Writes gpu/shaders/v3_blend_weights.glsl, the weights of the learned-blend nets: Settings::v3Blend 1, 2, 3 = nets A, B, C of the first weight set, 4, 5, 6 = nets A, B, C of the second.

    export_glsl.py A.npz B.npz C.npz  A2.npz B2.npz C2.npz [-o gpu/shaders/v3_blend_weights.glsl]     (first set, then second set; the committed header)
    export_glsl.py A.npz B.npz C.npz [-o ...]                                                             (three paths: the second set is written as zeros)
    export_glsl.py --zeros [-o ...]          (six zero nets: each net then equals the rule up to the 1e-3 floor)

Each .npz holds float32 W1 [8][NI], b1 [8], W2 [K][8], b2 [K]; A and B: NI 25, K 4; C: NI 34, K 6 (SPEC section 4; gpu/V3.md 3.16 "As built (learned blend)").
Layout of the header (variant v = 0..5 for v3Blend 1..6 (v = 0, 1, 2 the first set's A, B, C, v = 3, 4, 5 the second's); every net padded with zeros to NI 34, K 6):
    V3B_W1[(v*8 + j)*34 + i]   V3B_B1[v*8 + j]   V3B_W2[(v*6 + k)*8 + j]   V3B_B2[v*6 + k]
"""
import argparse, os, sys
import numpy as np

H, NIMAX, KMAX = 8, 34, 6
SHAPES = [(25, 4), (25, 4), (34, 6)] * 2

def load(path, ni, k):
    z = np.load(path)
    w1, b1, w2, b2 = (np.asarray(z[n], np.float32) for n in ("W1", "b1", "W2", "b2"))
    for name, a, shape in (("W1", w1, (H, ni)), ("b1", b1, (H,)), ("W2", w2, (k, H)), ("b2", b2, (k,))):
        if a.shape != shape:
            sys.exit(f"{path}: {name} has shape {a.shape}, expected {shape}")
        if not np.all(np.isfinite(a)):
            sys.exit(f"{path}: {name} is not finite")
    return w1, b1, w2, b2

def pad(nets):
    W1 = np.zeros((6, H, NIMAX), np.float32); B1 = np.zeros((6, H), np.float32)
    W2 = np.zeros((6, KMAX, H), np.float32); B2 = np.zeros((6, KMAX), np.float32)
    for v, (w1, b1, w2, b2) in enumerate(nets):
        W1[v, :, :w1.shape[1]] = w1; B1[v] = b1
        W2[v, :w2.shape[0]] = w2; B2[v, :b2.shape[0]] = b2
    return W1, B1, W2, B2

def arr(name, a):
    f = a.reshape(-1)
    body = ",\n    ".join(", ".join(repr(float(x)) if x != 0 else "0.0" for x in f[i:i + 8]) for i in range(0, len(f), 8))
    return f"const float {name}[{len(f)}] = float[{len(f)}](\n    {body});\n"

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("npz", nargs="*")
    ap.add_argument("--zeros", action="store_true")
    ap.add_argument("-o", default=os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "shaders", "v3_blend_weights.glsl"))
    a = ap.parse_args()
    if a.zeros:
        nets = [(np.zeros((H, ni), np.float32), np.zeros(H, np.float32), np.zeros((k, H), np.float32), np.zeros(k, np.float32)) for ni, k in SHAPES]
    elif len(a.npz) in (3, 6):
        nets = [load(p, ni, k) for p, (ni, k) in zip(a.npz, SHAPES)]
        nets += [(np.zeros((H, ni), np.float32), np.zeros(H, np.float32), np.zeros((k, H), np.float32), np.zeros(k, np.float32)) for ni, k in SHAPES[len(nets):]]
    else:
        sys.exit("usage: export_glsl.py A.npz B.npz C.npz [A2.npz B2.npz C2.npz] [-o out.glsl]   or   --zeros")
    W1, B1, W2, B2 = pad(nets)
    out = ("// GENERATED by gpu/ml/blend/export_glsl.py (" + ("all zeros: every net equals the rule up to the 1e-3 floor" if a.zeros else "weights of A, B, C" + (" and A, B, C of the second set" if len(a.npz) == 6 else "")) + "). Do not edit.\n"
           "// Variant v = 0..5 (Settings::v3Blend 1..6: A, B, C of the first set, then of the second), every net padded with zeros to NI 34, K 6 (gpu/V3.md 3.16 \"As built (learned blend)\"):\n"
           "//   V3B_W1[(v*8 + j)*34 + i]  V3B_B1[v*8 + j]  V3B_W2[(v*6 + k)*8 + j]  V3B_B2[v*6 + k]\n"
           + arr("V3B_W1", W1) + arr("V3B_B1", B1) + arr("V3B_W2", W2) + arr("V3B_B2", B2))
    with open(a.o, "w") as f:
        f.write(out)

if __name__ == "__main__":
    main()
